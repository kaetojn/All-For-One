"""Build the exercise library from a checkout of github.com/yuhonas/free-exercise-db (public domain).

    python3 scripts/build-exercises.py /path/to/free-exercise-db

Writes worker/exercise-data.js (the catalogue) and public/exercises/<id>/0.webp and 1.webp
(start and end positions, shrunk for phones). Run it again only to refresh the library.
"""
import json, re, sys
from pathlib import Path
from PIL import Image

src = Path(sys.argv[1])
root = Path(__file__).resolve().parent.parent
out_images = root / 'public' / 'exercises'
KEEP = {'strength', 'plyometrics', 'cardio', 'stretching'}

items = []
for e in json.loads((src / 'dist' / 'exercises.json').read_text()):
    if e['category'] not in KEEP or len(e['images']) != 2:
        continue
    slug = re.sub(r'[^A-Za-z0-9]+', '-', e['id']).strip('-').lower()
    folder = out_images / slug
    folder.mkdir(parents=True, exist_ok=True)
    for i, image in enumerate(e['images']):
        target = folder / f'{i}.webp'
        if not target.exists():
            im = Image.open(src / 'exercises' / image).convert('RGB')
            im.thumbnail((440, 440))
            im.save(target, 'WEBP', quality=62, method=6)
    items.append({
        'id': slug,
        'name': e['name'],
        'level': e['level'],
        'equipment': e['equipment'] or 'body only',
        'category': e['category'],
        'compound': e['mechanic'] == 'compound',
        'force': e['force'],
        'muscles': e['primaryMuscles'],
        'also': e['secondaryMuscles'],
        'steps': e['instructions'],
    })

assert len({i['id'] for i in items}) == len(items), 'duplicate ids'
body = ',\n'.join(json.dumps(i, ensure_ascii=False, separators=(',', ':')) for i in items)
(root / 'worker' / 'exercise-data.js').write_text(
    '// Generated by scripts/build-exercises.py from github.com/yuhonas/free-exercise-db (public domain). Do not edit by hand.\n'
    f'export default [\n{body}\n];\n')
print(len(items), 'exercises')
